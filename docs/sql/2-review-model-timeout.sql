-- =============================================
-- CodeFreeX 增量脚本 2：预审核模型超时调优
-- =============================================
-- 说明：
-- 1. 本脚本为增量变更，请在已执行 init.sql 及脚本 1 的库上执行一次，可重复执行（幂等）。
-- 2. 背景：工具调用循环（可视化编辑/普通编辑/代码修复）走同步模型调用，
--    推理型模型在大上下文下单次响应可超过 300s，触发 JDK HttpClient 超时后
--    由 langchain4j 重试兜底，但超时等待的时间被浪费、整轮耗时翻倍。
--    将预审核模型超时从 300s 调整为 600s，让慢轮次一次完成而非"超时+重试"。
-- =============================================

USE codefreex;

UPDATE system_config
SET config_value = '600'
WHERE config_key = 'ai.review.timeout-seconds'
  AND is_delete = 0;
